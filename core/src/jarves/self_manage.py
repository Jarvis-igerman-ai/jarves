"""Self-management (owner request 21 Oct 2026): JARVES manages ITSELF on demand, by voice, text, CLI or dashboard.

What it adds is a thin layer over what already exists (no second implementation of anything):

    read    connections (the `jarvis connect` checklist), features, skills (built-in + generated), memory, workspace
            files, what could be improved, history of changes
    change  edit a section of SOUL / IDENTITY / USER / MEMORY / AGENTS (.md), add or remove a memory item, switch a
            feature or a generated skill, change an allow-listed setting, start the guided connection of an account
    undo    the last change (or one by id): `jarvis undo`, "undo that", the dashboard History list

Rules (enforced here and by the registry, never by prompt text):
- EVERY change shows the approval popup (approvals.py, one service for popup / tray / face / dashboard / voice) with a
  plain BEFORE / AFTER text; spoken approvals name only the kind of action (approvals.spoken_kind).
- EVERY change is backed up first and undoable: files through the workspace history, the other kinds through a small
  journal (<home>/self_manage/changes.json) that keeps the previous value. An undo is itself an approved change.
- EVERY change is audited with fixed-literal log messages (logs.py rules): never the text that was written.
- Never reachable from here: secrets (secrets.env, tokens, API keys, any text that looks like one is refused), TOOLS /
  SETUP / FEATURES.md (generated), the approvals policy itself, permission and safety switches (PROTECTED_FEATURES,
  PROTECTED_RX), settings that are not on the settings allow-list, built-in skills (they follow their feature).
- Taint: the change tools are "destructive" model tools, so after the assistant read text written by others (web page,
  mail, message, agent output) in this turn the registry refuses them (TOOL_UNTRUSTED_TURN).
- A key or token for an account is never spoken or typed in chat: `self_connect` opens the guided `jarvis connect`
  window, whose hidden-input flow takes it.

Connection checks use `connect.status_items` (local files and one localhost probe). `CHECKER` is the thin interface for
`jarvis connect --check` (another branch): when `connect.check_items` exists it is used instead.
"""
