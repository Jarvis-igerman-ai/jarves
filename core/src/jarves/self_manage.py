def _terminal_approve(home: Path) -> Callable[[Plan], bool]:
    """The CLI approval: the same BEFORE / AFTER text, typed `yes` in this terminal (never via --yes), audited to the
    same approvals audit file as every other decision."""
    from . import approvals

    def ask(prompt: str) -> bool:
        if not sys.stdin or not sys.stdin.isatty():
            print(clilang.fmt("נדרש אישור שלך בטרמינל אינטראקטיבי: לא בוצע.",
                              "Your approval is needed in an interactive terminal: nothing was changed."), file=sys.stderr)
            return False
        print(prompt)
        return input("Approve? type yes: ").strip().lower() in ("yes", "y", "כן")

    import asyncio
    audited = approvals.audited(home, lambda p: asyncio.sleep(0, result=ask(p)))

    def approve(plan: Plan) -> bool:
        return bool(asyncio.run(audited(plan.prompt, title="self_manage_" + plan.what, kind="other", risk="medium",
                                        source="user")))
    return approve


def cmd_manage(a, cfg, home) -> int:
    logs.setup(Path(home) / "logs", cfg.log.level, console=False, privacy=cfg.log.privacy)
    cmd = "undo" if a.cmd == "undo" else a.mcmd
    mgr, close = build_manager(cfg, Path(home))
    try:
        if cmd == "status":
            st = mgr.status(a.area)
            if a.json:
                print(json.dumps(st, ensure_ascii=False, indent=1))
            else:
                print(mgr.summarize(st))
                for c in st.get("connections", []):
                    print(f"  {c.get('id'):<10} {c.get('state'):<10} {c.get('detail_en', '')}"
                          + (f"  -> {c['fix_en']}" if c.get("state") != "connected" and c.get("fix_en") else ""))
            return 0
        if cmd == "history":
            for e in mgr.history(a.n):
                when = time.strftime("%Y-%m-%d %H:%M", time.localtime(e["ts"]))
                print(f"{e['id']}  {when}  {e['by']:<9} {e['summary']}" + ("  [undone]" if e.get("undone") else "")
                      + ("" if e.get("undoable") else "  [no undo]"))
            return 0
        approve = _terminal_approve(Path(home))
        if cmd == "file":
            text = sys.stdin.read() if a.text == "-" else a.text
            plan = mgr.plan("file", a.name, text, a.section, a.mode, by="cli")
        elif cmd == "memory":
            plan = mgr.plan("memory_add" if a.op == "add" else "memory_remove", "", a.value) if a.op == "add" \
                else mgr.plan("memory_remove", a.value)
        elif cmd in ("feature", "skill"):
            plan = mgr.plan(cmd, a.id, a.state, by="cli")
        elif cmd == "setting":
            plan = mgr.plan("setting", a.key, a.value, by="cli")
        elif cmd == "connect":
            plan = mgr.plan_connect(a.which)
        elif cmd == "undo":
            plan = mgr.plan_undo(a.id)
        else:
            return 2
        res = mgr.run(plan, approve, by="cli")
        print(res["message"])
        return 0 if res["ok"] else 1
    except Refused as r:
        print(f"Not done ({r.code}): {r.message}", file=sys.stderr)
        return 1
    finally:
        close()


