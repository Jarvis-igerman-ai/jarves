class StatusArgs(BaseModel):
    area: Literal["all", "connections", "features", "skills", "memory", "files", "improve", "history"] = "all"


class ChangeArgs(BaseModel):
    what: Literal["file", "memory_add", "memory_remove", "feature", "skill", "setting"]
    target: str = Field("", max_length=60, description="file name | memory id | feature id | skill id | setting key")
    value: str = Field("", max_length=MAX_TEXT, description="the text, or on/off, or the setting value")
    section: str = Field("", max_length=60, description="heading of the section (files)")
    mode: Literal["append", "replace_section", "remove_section", "replace_file"] = "append"


class ConnectArgs(BaseModel):
    which: str = Field("", max_length=20, description="google telegram pear wake instagram home; empty = all")


class UndoArgs(BaseModel):
    change_id: str = Field("", max_length=20, description="empty = the last change")


def make_skill(mgr: SelfManager) -> Skill:
    def refusal(r: Refused) -> ToolResult:
        return ToolResult(False, r.message, code=r.code)

    async def status(a: StatusArgs):
        try:
            st = mgr.status(a.area)
        except Refused as r:
            return refusal(r)
        return ToolResult(True, mgr.summarize(st), st)

    def pre_change(a: ChangeArgs):
        try:
            mgr.plan(a.what, a.target, a.value, a.section, a.mode, by="voice")
        except Refused as r:
            if r.code == "NO_CHANGE":
                return ToolResult(True, r.message, code="NO_CHANGE")
            return refusal(r)
        return None

    async def impact_change(a: ChangeArgs):
        return None, mgr.plan(a.what, a.target, a.value, a.section, a.mode, by="voice").prompt

    def meta_change(a: ChangeArgs) -> dict:
        return {"details": {"change": a.what, "target": a.target[:40] if a.what != "memory_add" else ""},
                "why": "You asked JARVES to change itself."}

    async def change(a: ChangeArgs):
        try:
            res = mgr.apply(mgr.plan(a.what, a.target, a.value, a.section, a.mode, by="voice"), by="voice")
        except Refused as r:
            return refusal(r)
        return ToolResult(True, res["message"], {"change_id": res["id"]})

    def pre_connect(a: ConnectArgs):
        try:
            mgr.plan_connect(a.which)
        except Refused as r:
            return refusal(r)
        return None

    async def impact_connect(a: ConnectArgs):
        return None, mgr.plan_connect(a.which).prompt

    async def connect(a: ConnectArgs):
        try:
            res = mgr.apply(mgr.plan_connect(a.which), by="voice")
        except Refused as r:
            return refusal(r)
        return ToolResult(True, res["message"], {"command": res["command"], "started": res["started"]})

    def pre_undo(a: UndoArgs):
        try:
            mgr.plan_undo(a.change_id)
        except Refused as r:
            return refusal(r)
        return None

    async def impact_undo(a: UndoArgs):
        return None, mgr.plan_undo(a.change_id).prompt

    async def undo(a: UndoArgs):
        try:
            res = mgr.apply(mgr.plan_undo(a.change_id), by="voice")
        except Refused as r:
            return refusal(r)
        return ToolResult(True, res["message"], {})

    meta_simple = lambda _a: {"why": "You asked JARVES to change itself."}

    class SelfManageSkill(Skill):
        name = "self_manage"
        description = "Manage myself: connections, features, skills, my files, memory, settings, undo"

        def tools(self) -> list[Tool]:
            return [
                Tool("self_status", "My own state: connections (what is connected / broken), features, skills, memory, "
                                    "my files, what to improve. 'מה מחובר?' 'what can be improved?'",
                     status, StatusArgs, permission="read", timeout_s=20),
                Tool("self_change", "Change myself, owner approves on screen: edit an .md section (SOUL/IDENTITY/USER/"
                                    "MEMORY/AGENTS), add/forget memory, feature or skill on/off, a setting. "
                                    "'תוסיף ל-USER' 'turn off X'. Never secrets.",
                     change, ChangeArgs, permission="destructive", impact=impact_change, precheck=pre_change,
                     approval_meta=meta_change, timeout_s=300),
                Tool("self_connect", "Start guided connecting/fixing of an account (window opens; secrets typed there, "
                                     "never in chat). 'תחבר את X' 'fix Telegram'",
                     connect, ConnectArgs, permission="destructive", impact=impact_connect, precheck=pre_connect,
                     approval_meta=meta_simple),
                Tool("self_undo", "Undo my last self-change. 'בטל את זה' 'undo that'",
                     undo, UndoArgs, permission="destructive", impact=impact_undo, precheck=pre_undo,
                     approval_meta=meta_simple),
            ]

    return SelfManageSkill()


