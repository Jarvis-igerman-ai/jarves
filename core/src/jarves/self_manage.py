def protected_feature(fid: str) -> bool:
    return fid in PROTECTED_FEATURES or bool(PROTECTED_RX.search(fid))


def _clip(text: str, n: int = 400) -> str:
    text = str(text)
    return text if len(text) <= n else text[: n - 1].rstrip() + "…"


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:24]


def _looks_secret(text: str) -> bool:
    return bool(_SECRET.search(text)) or logs.redact(text) != text


def _lines_changed(old: str, new: str) -> tuple[str, str]:
    """Plain BEFORE / AFTER of a text edit: only the lines that differ (a few lines of each)."""
    a, b = old.splitlines(), new.splitlines()
    gone, came = [], []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag in ("replace", "delete"):
            gone += a[i1:i2]
        if tag in ("replace", "insert"):
            came += b[j1:j2]
    gone, came = [l for l in gone if l.strip()], [l for l in came if l.strip()]
    show = lambda ls: _clip("\n".join(ls[:12]) + (f"\n(+{len(ls) - 12} more lines)" if len(ls) > 12 else ""), 900)
    return show(gone) or "(nothing)", show(came) or "(nothing)"


def _prompt(title: str, before: str, after: str, note: str = "") -> str:
    return f"{title}\n\nBEFORE:\n{before}\n\nAFTER:\n{after}" + (f"\n\n{note}" if note else "")


# ---------------------------------------------------------------------- markdown section editing
def _find_section(lines: list[str], section: str) -> tuple[int, int] | None:
    want = section.strip().lstrip("#").strip().lower()
    for i, line in enumerate(lines):
        m = _HEAD.match(line)
        if m and m.group(2).strip().lower() == want:
            return i, len(m.group(1))
    return None


def _section_end(lines: list[str], i: int, level: int) -> int:
    j = i + 1
    while j < len(lines):
        m = _HEAD.match(lines[j])
        if m and len(m.group(1)) <= level:
            break
        j += 1
    return j


def edit_text(old: str, mode: str, section: str, text: str) -> str:
    """The new file text for one edit. append: add a block (under `section`, created when missing); replace_section /
    remove_section: the body of the '## section' heading; replace_file: the whole file."""
    old = old.replace("\r\n", "\n")
    block = text.strip("\n")
    section = " ".join(section.split())
    if mode == "replace_file":
        return block.strip() + "\n"
    lines = old.rstrip("\n").split("\n") if old.strip() else []
    found = _find_section(lines, section) if section else None
    if mode == "append":
        if not block.strip():
            raise Refused("BAD_ARGS", "there is nothing to add")
        if not section:
            return ("\n".join(lines) + "\n" if lines else "") + block + "\n"
        if found is None:
            return ("\n".join(lines) + "\n\n" if lines else "") + f"## {section}\n{block}\n"
        end = _section_end(lines, *found)
        while end > found[0] + 1 and not lines[end - 1].strip():
            end -= 1
        return "\n".join(lines[:end] + block.split("\n") + [""] + lines[end:]).rstrip("\n") + "\n"
    if not section:
        raise Refused("BAD_ARGS", "name the section (its heading) to edit")
    if mode == "replace_section":
        if not block.strip():
            raise Refused("BAD_ARGS", "give the new text of the section (or use remove_section)")
        if found is None:
            return ("\n".join(lines) + "\n\n" if lines else "") + f"## {section}\n{block}\n"
        end = _section_end(lines, *found)
        tail = lines[end:]
        return "\n".join(lines[: found[0] + 1] + block.split("\n") + ([""] if tail else []) + tail).rstrip("\n") + "\n"
    if mode == "remove_section":
        if found is None:
            raise Refused("NOT_FOUND", f"there is no section '{_clip(section, 40)}'")
        end = _section_end(lines, *found)
        rest = lines[: found[0]] + lines[end:]
        return ("\n".join(rest).rstrip("\n") + "\n") if any(x.strip() for x in rest) else ""
    raise Refused("BAD_ARGS", f"mode must be one of: {', '.join(MODES)}")


# ---------------------------------------------------------------------- connections (thin interface)
def default_check(home: Path, cfg, only: str | None = None) -> list[dict]:
    """The `jarvis connect` checklist as dicts. `connect.check_items(home, cfg, only)` (the --check logic of another
    branch) is used when present; until then the local `status_items` (files + one localhost probe, no accounts)."""
    from . import connect
    fn = getattr(connect, "check_items", None)
    items = fn(home, cfg, only) if callable(fn) else connect.status_items(home, cfg)
    out = []
    for it in items:
        d = asdict(it) if hasattr(it, "__dataclass_fields__") else dict(it)
        if only and d.get("id") != only:
            continue
        out.append({k: (logs.redact(v) if isinstance(v, str) else v) for k, v in d.items()})
    return out


def default_start(which: str | None) -> bool:
    """Open `jarvis connect [--only X]` in its own console window (it takes the keyboard and its hidden-input prompts).
    Windows only; elsewhere False (the answer then tells the owner to run the command in a terminal)."""
    if sys.platform != "win32":
        return False
    args = [sys.executable, "-m", "jarves", "connect"] + (["--only", which] if which else [])
    subprocess.Popen(args, creationflags=subprocess.CREATE_NEW_CONSOLE)
    return True


def connect_command(which: str | None) -> str:
    return "jarvis connect" + (f" --only {which}" if which else "")


# ---------------------------------------------------------------------- the manager
class SelfManager:
    def __init__(self, home: Path, cfg=None, *, workspace, memory, settings, features=None,
                 generated: Callable[[], Any] | Any = None, registry=None,
                 check: Callable[..., list[dict]] | None = None, start: Callable[[str | None], bool] | None = None,
                 prepare: Callable[..., tuple[bool, str]] | None = None,
                 on_voice_change: Callable[[str, bool], None] | None = None,
                 clock: Callable[[], float] = time.time) -> None:
        self.home, self.cfg = Path(home), cfg
        self.ws, self.memory, self.settings, self.features = workspace, memory, settings, features
        self._generated = generated
        self.registry = registry
        self.check = check or default_check
        self.start = start or default_start
        self.prepare = prepare
        self.on_voice_change = on_voice_change
        self.clock = clock
        self._lock = threading.RLock()

    # ------------------------------------------------------------ journal (the previous value of every change)
    @property
    def journal_path(self) -> Path:
        return self.home / JOURNAL_DIR / JOURNAL_FILE

    def _load(self) -> list[dict]:
        try:
            raw = json.loads(self.journal_path.read_text(encoding="utf-8"))
            return [e for e in raw.get("changes", []) if isinstance(e, dict)]
        except (OSError, ValueError):
            return []

    def _save(self, changes: list[dict]) -> None:
        p = self.journal_path
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(".tmp")
        tmp.write_text(json.dumps({"changes": changes[-JOURNAL_KEEP:]}, ensure_ascii=False, indent=1), encoding="utf-8")
        os.replace(tmp, p)

    def _record(self, plan: Plan, undo: dict, by: str) -> str:
        cid = uuid.uuid4().hex[:10]
        with self._lock:
            ch = self._load()
            ch.append({"id": cid, "ts": round(self.clock(), 1), "kind": plan.kind or plan.what, "target": plan.target,
                       "summary": plan.summary, "before": plan.before, "after": plan.after, "by": by,
                       "undoable": bool(plan.undoable and undo), "undo": undo, "undone": False})
            self._save(ch)
        return cid

    def history(self, limit: int = 30) -> list[dict]:
        """Newest first; without the internal undo data."""
        rows = [{k: v for k, v in e.items() if k != "undo"} for e in self._load()]
        return list(reversed(rows))[:limit]

    def generated(self):
        g = self._generated() if callable(self._generated) else self._generated
        if g is None:
            from .skills.generated import GeneratedSkills
            g = GeneratedSkills(self.home)
        return g

    # ------------------------------------------------------------ reading
    def connections(self, only: str | None = None) -> list[dict]:
        try:
            rows = self.check(self.home, self.cfg, only)
        except Exception as e:
            logs.warn("self_manage", "SELF_MANAGE_CHECK_FAILED", "connection check failed", error_type=type(e).__name__)
            return [{"id": "check", "state": "attention", "title_en": "Connection check", "title_he": "בדיקת חיבורים",
                     "detail_en": f"the check could not run ({type(e).__name__})", "detail_he": "הבדיקה לא רצה",
                     "fix_en": "Run: " + connect_command(None), "fix_he": "להריץ: " + connect_command(None)}]
        return [{k: (logs.redact(v) if isinstance(v, str) else v) for k, v in dict(r).items()} for r in rows]

    def feature_rows(self) -> list[dict]:
        if self.features is None:
            return []
        rows = []
        for s in self.features.list(wait=False):
            rows.append({"id": s["id"], "title_en": s["title_en"], "title_he": s["title_he"],
                         "state": feat.state_word(s), "reason": logs.redact(s.get("reason") or ""), "risk": s["risk"],
                         "protected": protected_feature(s["id"])})
        return rows

    def skill_rows(self) -> dict:
        built_in = sorted(n for n in (self.registry.skills if self.registry is not None else {})
                          if n not in self._generated_ids())
        owner = {s: f.id for f in feat.CATALOG.values() for s in f.skills}
        gen = []
        try:
            for sid in self.generated().installed_ids():
                v = self.generated().view(sid)
                gen.append({"id": sid, "title": v.get("title", sid), "enabled": bool(v.get("enabled")),
                            "version": v.get("version"), "tools": len(v.get("tools") or [])})
        except Exception as e:
            logs.warn("self_manage", "SELF_MANAGE_SKILLS_FAILED", "generated skills unreadable", error_type=type(e).__name__)
        return {"built_in": [{"id": n, "feature": owner.get(n, "")} for n in built_in], "generated": gen}

    def _generated_ids(self) -> set[str]:
        try:
            return set(self.generated().installed_ids())
        except Exception:
            return set()

    def memory_rows(self, limit: int = 30) -> dict:
        items = self.memory.list(limit)
        return {"count": self.memory.count(),
                "items": [{"id": r["id"], "text": _clip(r["text"], 160), "source": r.get("source", "")} for r in items]}

    def file_rows(self) -> list[dict]:
        out = []
        for f in self.ws.files():
            out.append({"name": f["name"], "title": f["title"], "chars": f["chars"], "versions": f["versions"],
                        "generated": f["generated"], "editable": f["name"] in EDITABLE_FILES,
                        "modified": f["modified"]})
        return out

    def improvements(self) -> list[dict]:
        """Cheap local suggestions (no network, no model): what is not connected or not working and the next step."""
        out: list[dict] = []
        for c in self.connections():
            if c.get("state") in ("missing", "attention") and not c.get("optional"):
                out.append({"id": f"connect_{c['id']}", "area": "connections",
                            "en": f"{c.get('title_en', c['id'])}: {c.get('detail_en', c.get('state'))}",
                            "he": f"{c.get('title_he', c['id'])}: {c.get('detail_he', c.get('state'))}",
                            "action": f"self_connect {c['id']}" if c["id"] in _only() else ""})
        for r in self.feature_rows():
            if r["state"] == "unavailable":
                out.append({"id": f"feature_{r['id']}", "area": "features",
                            "en": f"{r['title_en']} is on but unavailable: {r['reason']}",
                            "he": f"{r['title_he']} דולקת אבל לא זמינה: {r['reason']}", "action": ""})
        try:
            if not _clean_body(self.ws.read("USER.md")):
                out.append({"id": "user_md_empty", "area": "files", "en": "USER.md is empty: tell me how to address you "
                            "and what you like", "he": "USER.md ריק: ספר לי איך לפנות אליך ומה אתה אוהב", "action": ""})
        except Exception:
            pass
        try:
            if self.memory.count() == 0:
                out.append({"id": "memory_empty", "area": "memory", "en": "I remember nothing about you yet",
                            "he": "אני עדיין לא זוכר עליך כלום", "action": ""})
        except Exception:
            pass
        try:
            for d in self.generated().draft_ids():
                out.append({"id": f"draft_{d}", "area": "skills", "en": f"A proposed skill waits for your review: {d}",
                            "he": f"כלי מוצע ממתין לבדיקה שלך: {d}", "action": ""})
        except Exception:
            pass
        return out

    def status(self, area: str = "all") -> dict:
        if area not in AREAS:
            raise Refused("BAD_ARGS", f"area must be one of: {', '.join(AREAS)}")
        want = lambda a: area in ("all", a)
        out: dict[str, Any] = {}
        if want("connections"):
            out["connections"] = self.connections()
        if want("features"):
            out["features"] = self.feature_rows()
        if want("skills"):
            out["skills"] = self.skill_rows()
        if want("memory"):
            out["memory"] = self.memory_rows()
        if want("files"):
            out["files"] = self.file_rows()
        if want("improve"):
            out["improve"] = self.improvements()
        if want("history"):
            out["history"] = self.history(20)
        return out

    @staticmethod
    def summarize(st: dict) -> str:
        parts = []
        if "connections" in st:
            ok = [c.get("title_en", c["id"]).split(" (")[0] for c in st["connections"] if c.get("state") == "connected"]
            bad = [f"{c.get('title_en', c['id']).split(' (')[0]} ({c.get('state')}: {c.get('detail_en', '')})"
                   for c in st["connections"] if c.get("state") != "connected"]
            parts.append("Connected: " + (", ".join(ok) or "none") + (". Not OK: " + "; ".join(bad) if bad else ""))
        if "features" in st:
            on = sum(1 for f in st["features"] if f["state"] == "on")
            un = [f["id"] for f in st["features"] if f["state"] == "unavailable"]
            parts.append(f"Features: {on} on of {len(st['features'])}" + (f"; unavailable: {', '.join(un)}" if un else ""))
        if "skills" in st:
            sk = st["skills"]
            parts.append(f"Skills: {len(sk['built_in'])} built in, {len(sk['generated'])} generated "
                         f"({sum(1 for g in sk['generated'] if g['enabled'])} enabled)")
        if "memory" in st:
            parts.append(f"Memory: {st['memory']['count']} items")
        if "files" in st:
            parts.append("Files: " + ", ".join(f["name"] for f in st["files"] if f["editable"]) + " (editable)")
        if "improve" in st:
            parts.append("Could improve: " + ("; ".join(i["en"] for i in st["improve"][:5]) or "nothing found"))
        if "history" in st:
            parts.append(f"Changes made: {len(st['history'])}")
        return ". ".join(parts)

    # ------------------------------------------------------------ planning (nothing changes here)
    def plan(self, what: str, target: str = "", value: str = "", section: str = "", mode: str = "append",
             by: str = "voice") -> Plan:
        target, value = str(target or "").strip(), str(value or "")
        if what == "file":
            return self._plan_file(target, mode, section, value, by)
        if what == "memory_add":
            return self._plan_memory_add(value or target)
        if what == "memory_remove":
            return self._plan_memory_remove(target)
        if what == "feature":
            return self._plan_feature(target, value)
        if what == "skill":
            return self._plan_skill(target, value)
        if what == "setting":
            return self._plan_setting(target, value)
        raise Refused("BAD_ARGS", f"what must be one of: {', '.join(WHATS)}")

    def _plan_file(self, name: str, mode: str, section: str, text: str, by: str) -> Plan:
        if mode not in MODES:
            raise Refused("BAD_ARGS", f"mode must be one of: {', '.join(MODES)}")
        try:
            fname = self.ws.path(name).name
        except WorkspaceError:
            raise Refused("UNKNOWN_FILE", "unknown file; editable: " + ", ".join(EDITABLE_FILES)) from None
        if SPECS[fname].generated:
            raise Refused("PROTECTED_FILE", PROTECTED_FILES_WHY)
        if fname not in EDITABLE_FILES:
            raise Refused("PROTECTED_FILE", f"{fname} cannot be changed from here; editable: " + ", ".join(EDITABLE_FILES))
        if len(text) > MAX_TEXT or len(section) > 60 or "\n" in section:
            raise Refused("BAD_ARGS", "the text or the section name is too long")
        if _looks_secret(text):
            raise Refused("SECRET_REFUSED", "this looks like a password, key or code; secrets are never written here")
        if by == "voice" and self.features is not None and not self.features.enabled("workspace_agent_edit"):
            raise Refused("FEATURE_OFF", "changing my files from a conversation is switched off (workspace_agent_edit)")
        old = self.ws.read(fname)
        new = edit_text(old, mode, section, text)
        try:
            self.ws.validate(fname, new, "user")
        except WorkspaceError as e:
            raise Refused("WORKSPACE_REFUSED", str(e)) from None
        if new.replace("\r\n", "\n") == old.replace("\r\n", "\n"):
            raise Refused("NO_CHANGE", f"{fname} would not change")
        before, after = _lines_changed(old, new)
        where = f" (section {section})" if section else ""
        verb = {"append": "Add to", "replace_section": "Rewrite a section of", "remove_section": "Remove a section of",
                "replace_file": "Replace the whole of"}[mode]
        return Plan("file", fname, f"{verb} {fname}{where}", before, after,
                    _prompt(f"{verb} {fname}{where}?", before, after, "A backup is kept; you can undo this."),
                    {"mode": mode, "section": section, "new": new}, kind="file")

    def _plan_memory_add(self, text: str) -> Plan:
        text = " ".join(text.split())
        if not text or len(text) > MAX_MEMORY:
            raise Refused("BAD_ARGS", f"a memory item is 1 to {MAX_MEMORY} characters")
        if _looks_secret(text):
            raise Refused("SECRET_REFUSED", "this looks like a password, key or code; secrets are never remembered")
        dup = self.memory.find_duplicate(text)
        if dup is not None:
            raise Refused("NO_CHANGE", "I already remember that")
        return Plan("memory_add", "", "Remember a new item", "(not remembered)", text,
                    _prompt("Remember this?", "(not remembered)", text, "You can undo this."), {"text": text},
                    kind="memory_add")

    def _plan_memory_remove(self, target: str) -> Plan:
        if not target.isdigit():
            raise Refused("BAD_ARGS", "give the number of the memory item (see the memory list)")
        row = self.memory.get(int(target))
        if row is None:
            raise Refused("NOT_FOUND", f"there is no memory item {target}")
        return Plan("memory_remove", target, f"Forget memory item {target}", _clip(row["text"], 500), "(forgotten)",
                    _prompt("Forget this?", _clip(row["text"], 500), "(forgotten)", "You can undo this."),
                    {"row": {k: row.get(k) for k in ("text", "source", "confidence", "kind")}}, kind="memory_remove")

    @staticmethod
    def _bool(value: str) -> bool:
        v = str(value).strip().lower()
        if v in _TRUE:
            return True
        if v in _FALSE:
            return False
        raise Refused("BAD_ARGS", "value must be on or off")

    def _plan_feature(self, fid: str, value: str) -> Plan:
        fid = fid.lower()
        if fid not in feat.CATALOG:
            raise Refused("UNKNOWN_FEATURE", "unknown feature; see self_status features")
        if protected_feature(fid):
            raise Refused("PROTECTED_FEATURE", f"{fid} is a permission or safety switch; only the owner changes it on the "
                                               "Features page or with `jarvis features`")
        if self.features is None:
            raise Refused("NOT_READY", "features are not available right now")
        on = self._bool(value)
        f = feat.CATALOG[fid]
        st = self.features.status(fid)
        if bool(st["enabled"]) == on:
            raise Refused("NO_CHANGE", f"{f.title_en} is already {'on' if on else 'off'}")
        before = feat.state_text(st, "en")
        after = ("on" if on else "off") + f" (applies {feat.APPLIES_EN[f.applies]})"
        return Plan("feature", fid, f"Turn {f.title_en} {'on' if on else 'off'}", before, after,
                    _prompt(f"Turn {f.title_en} {'on' if on else 'off'}?", before, after,
                            (f.about[:200] + "\n" if on and f.about else "") + "You can undo this."),
                    {"on": on, "explicit": st.get("source", "default") != "default", "prev": bool(st["enabled"])},
                    kind="feature")

    def _plan_skill(self, sid: str, value: str) -> Plan:
        sid = sid.lower()
        on = self._bool(value)
        gen = self.generated()
        if sid not in gen.installed_ids():
            owner = next((f.id for f in feat.CATALOG.values() if sid in f.skills), "")
            if owner or (self.registry is not None and sid in self.registry.skills):
                raise Refused("BUILTIN_SKILL", f"{sid} is a built-in skill" + (f"; switch its feature {owner} instead"
                                                                              if owner else " and cannot be switched off"))
            raise Refused("UNKNOWN_SKILL", "unknown skill; see self_status skills")
        v = gen.view(sid)
        if bool(v.get("enabled")) == on:
            raise Refused("NO_CHANGE", f"{sid} is already {'on' if on else 'off'}")
        before, after = ("on" if v.get("enabled") else "off"), ("on" if on else "off")
        return Plan("skill", sid, f"Turn the skill {sid} {after}", before, after,
                    _prompt(f"Turn the generated skill '{sid}' {after}?", before, after,
                            (_clip(v.get("summary_en") or v.get("description") or "", 300) + "\n" if on else "")
                            + "You can undo this."),
                    {"on": on, "prev": bool(v.get("enabled"))}, kind="skill")

    def _plan_setting(self, key: str, value: str) -> Plan:
        from .skills.settings import ALLOWED
        key = key.strip().lower()
        if key not in ALLOWED or PROTECTED_RX.search(key):
            raise Refused("SETTING_NOT_ALLOWED", "that setting cannot be changed from here; allowed: " + ", ".join(ALLOWED))
        about, choices, _ = ALLOWED[key]
        value = value.strip().lower()
        if choices is not None and value not in choices:
            raise Refused("BAD_ARGS", f"{key} must be one of: {', '.join(choices)}")
        cur = self.settings.get(key)
        if cur == value:
            raise Refused("NO_CHANGE", f"{key} is already {value}")
        return Plan("setting", key, f"Change {key}", f"{key} = {cur or '(default)'}", f"{key} = {value}",
                    _prompt(f"Change the setting {key}?", f"{key} = {cur or '(default)'}", f"{key} = {value}",
                            about + "\nYou can undo this."),
                    {"value": value, "prev_override": self.memory.get_setting(f"override:{key}")}, kind="setting")

    def plan_connect(self, which: str | None) -> Plan:
        which = (which or "").strip().lower() or None
        if which and which not in _only():
            raise Refused("UNKNOWN_CONNECTION", "unknown account; one of: " + ", ".join(_only()))
        cmd = connect_command(which)
        return Plan("connect", which or "all", f"Open the guided connection window ({cmd})", "(not started)",
                    f"a window with `{cmd}` opens",
                    _prompt(f"Open the guided connection window for {which or 'your accounts'}?", "(not started)",
                            f"a window with `{cmd}` opens",
                            "Any key or token is typed THERE (hidden), never into chat or spoken."),
                    {"which": which}, undoable=False, kind="connect")

    def plan_undo(self, change_id: str = "") -> Plan:
        ch = self._load()
        cands = [e for e in reversed(ch) if e.get("undoable") and not e.get("undone")]
        e = next((x for x in cands if x["id"] == change_id), None) if change_id else (cands[0] if cands else None)
        if e is None:
            raise Refused("NOTHING_TO_UNDO", "there is no change to undo" if not change_id else "that change cannot be undone")
        u = e["undo"]
        if e["kind"] == "file":
            if self.ws.read(u["file"]) and _sha(self.ws.read(u["file"])) != u["after_sha"]:
                raise Refused("CHANGED_SINCE", f"{u['file']} was changed again after that; restore a version from the "
                                               "Persona files page instead")
        return Plan("undo", e["id"], f"Undo: {e['summary']}", e.get("after", ""), e.get("before", ""),
                    _prompt(f"Undo this change: {e['summary']}?", e.get("after", "") or "(nothing)",
                            e.get("before", "") or "(nothing)", "A backup is kept."),
                    {"entry": e}, undoable=False, kind="undo")

    # ------------------------------------------------------------ applying (only after the owner approved)
    def apply(self, plan: Plan, *, by: str = "voice") -> dict:
        """Do an APPROVED plan: back up, change, journal, audit. Returns {ok, message, id, ...}; never the written text."""
        try:
            res = self._apply(plan, by)
        except Refused as r:
            logs.warn("self_manage", "SELF_MANAGE_REFUSED", "change refused at apply", kind=plan.what, result_code=r.code, by=by)
            raise
        except Exception as e:
            logs.error("self_manage", "SELF_MANAGE_FAILED", "change failed", kind=plan.what, error_type=type(e).__name__,
                       exc=True)
            raise Refused("CHANGE_FAILED", f"the change failed ({type(e).__name__}); nothing was left half done") from None
        logs.info("self_manage", "SELF_MANAGE_CHANGED", "self-management change applied", kind=plan.what,
                  target=plan.target if plan.what != "memory_add" else "", by=by, id=res.get("id", ""))
        return res

    def _apply(self, p: Plan, by: str) -> dict:
        d = p.data
        undo: dict = {}
        note = ""
        if p.what == "file":
            r = self.ws.write(p.target, d["new"], by="user", note="self_manage")
            if not r["changed"]:
                raise Refused("NO_CHANGE", f"{p.target} would not change")
            undo = {"file": p.target, "version": r["version"], "after_sha": _sha(self.ws.read(p.target))}
            msg = f"Done: {p.summary}. A backup was kept; say 'undo that' to go back."
        elif p.what == "memory_add":
            mid = self.memory.add(d["text"], source="user")
            undo = {"memory_id": mid}
            msg = "Remembered. Say 'undo that' to forget it again."
        elif p.what == "memory_remove":
            if not self.memory.delete(int(p.target)):
                raise Refused("NOT_FOUND", "that memory item is already gone")
            undo = {"row": d["row"]}
            msg = "Forgotten. Say 'undo that' to bring it back."
        elif p.what == "feature":
            if d["on"] and self.prepare is not None:
                try:
                    ok, detail = self.prepare(p.target, self.features, self.home)
                except Exception as e:
                    ok, detail = False, f"prerequisite check failed ({type(e).__name__})"
                if not ok:
                    note = f" Prerequisite not ready: {logs.redact(str(detail))[:200]}."
            st = feat.switch(self.features, p.target, d["on"], by="voice" if by == "voice" else by)
            undo = {"id": p.target, "prev": d["prev"], "explicit": d["explicit"]}
            msg = f"{feat.CATALOG[p.target].title_en} is now {feat.state_text(st, 'en')}.{note}"
        elif p.what == "skill":
            self.generated().set_enabled(p.target, d["on"], by="user")
            undo = {"id": p.target, "prev": d["prev"]}
            msg = f"The skill {p.target} is now {'on' if d['on'] else 'off'} (takes effect within a few seconds)."
        elif p.what == "setting":
            self.settings.set(p.target, d["value"])
            if p.target == "voice.voice" and self.on_voice_change is not None:
                self.on_voice_change(d["value"], False)
            undo = {"key": p.target, "prev_override": d["prev_override"]}
            msg = f"Changed {p.target} to {d['value']}."
        elif p.what == "connect":
            which = d["which"]
            started = bool(self.start(which))
            cmd = connect_command(which)
            msg = (f"A window with `{cmd}` opened. Follow the steps there; type any key or token there (hidden), never "
                   "here in chat." if started else
                   f"Open a terminal and run: {cmd}. Type any key or token there (hidden), never here in chat.")
            cid = self._record(p, {}, by)
            logs.info("self_manage", "SELF_MANAGE_CONNECT", "guided connection started", target=which or "all",
                      ok=started, by=by)
            return {"ok": True, "message": msg, "id": cid, "started": started, "command": cmd}
        elif p.what == "undo":
            return self._apply_undo(p, by)
        else:
            raise Refused("BAD_ARGS", "unknown change")
        cid = self._record(p, undo, by)
        return {"ok": True, "message": msg, "id": cid, "summary": p.summary}

    def _apply_undo(self, p: Plan, by: str) -> dict:
        e = p.data["entry"]
        u, kind = e["undo"], e["kind"]
        if kind == "file":
            cur = self.ws.read(u["file"])
            if cur and _sha(cur) != u["after_sha"]:
                raise Refused("CHANGED_SINCE", f"{u['file']} was changed again after that")
            self.ws.restore(u["file"], u["version"], by="user")
        elif kind == "memory_add":
            self.memory.delete(int(u["memory_id"]))
        elif kind == "memory_remove":
            r = u["row"]
            self.memory.add(r["text"], source=r.get("source") or "user", confidence=float(r.get("confidence") or 1.0),
                            kind=r.get("kind") or "fact")
        elif kind == "feature":
            if u.get("explicit"):
                feat.switch(self.features, u["id"], bool(u["prev"]), by=by)
            else:
                self.features.reset(u["id"])
        elif kind == "skill":
            self.generated().set_enabled(u["id"], bool(u["prev"]), by="user")
        elif kind == "setting":
            if u.get("prev_override") is None:
                self.settings.reset(u["key"])
            else:
                self.memory.set_setting(f"override:{u['key']}", u["prev_override"])
        else:
            raise Refused("NOTHING_TO_UNDO", "that change cannot be undone")
        with self._lock:
            ch = self._load()
            for x in ch:
                if x["id"] == e["id"]:
                    x["undone"] = True
            self._save(ch)
        cid = self._record(p, {}, by)
        logs.info("self_manage", "SELF_MANAGE_UNDONE", "self-management change undone", kind=kind, by=by)
        return {"ok": True, "message": f"Undone: {e['summary']}.", "id": cid, "undid": e["id"]}

    # ------------------------------------------------------------ plan + ask + apply (CLI and dashboard)
    def run(self, plan: Plan, approve: Callable[[Plan], bool], *, by: str) -> dict:
        """The owner-facing path: ask (the same approval text), then apply. A refusal to approve changes nothing."""
        if not approve(plan):
            logs.info("self_manage", "SELF_MANAGE_DECLINED", "owner did not approve the change", kind=plan.what, by=by)
            return {"ok": False, "code": "DECLINED", "message": "Not approved: nothing was changed."}
        return self.apply(plan, by=by)


