"""Aggregate flake-report.json files (one per CI run) into docs/reviews/FLAKES.md and list quarantine candidates.

Usage: python tools/flake_report.py REPORT.json [...] [--out docs/reviews/FLAKES.md] [--history flakes-history.json]
History is a list of {"date": ISO, "test": id, "passed_on_retry": bool}; new reports are appended with today's date.
Rule: a test that flaked twice within 7 days is a quarantine candidate (add @pytest.mark.quarantine and open an issue)."""
from __future__ import annotations

import argparse
import datetime as dt
import json
from collections import Counter
from pathlib import Path

WINDOW_DAYS, THRESHOLD = 7, 2


def quarantine_candidates(history: list[dict], today: dt.date) -> list[str]:
    cut = today - dt.timedelta(days=WINDOW_DAYS)
    c = Counter(h["test"] for h in history if dt.date.fromisoformat(h["date"]) >= cut and h.get("passed_on_retry"))
    return sorted(t for t, n in c.items() if n >= THRESHOLD)


def render(history: list[dict], today: dt.date) -> str:
    counts = Counter(h["test"] for h in history)
    lines = ["# Test flakes", "", "Generated by `core/tools/flake_report.py` from CI `flake-report.json` artifacts.",
             "Rule: flaked twice in 7 days -> `@pytest.mark.quarantine` (runs in the non-blocking quarantine job, never skipped) "
             "+ an issue per test. See docs/CI_DETERMINISM.md.", "", "| Test | Flakes | Last seen |", "|---|---|---|"]
    for t, n in counts.most_common():
        last = max(h["date"] for h in history if h["test"] == t)
        lines.append(f"| `{t}` | {n} | {last} |")
    if not counts:
        lines.append("| (none recorded) | 0 | |")
    cands = quarantine_candidates(history, today)
    lines += ["", "## Quarantine candidates", ""] + ([f"- `{t}`" for t in cands] or ["- none"])
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("reports", nargs="*")
    ap.add_argument("--out", default="docs/reviews/FLAKES.md")
    ap.add_argument("--history", default="flakes-history.json")
    a = ap.parse_args()
    today = dt.date.today()
    hp = Path(a.history)
    history = json.loads(hp.read_text(encoding="utf-8")) if hp.exists() else []
    for r in a.reports:
        for e in json.loads(Path(r).read_text(encoding="utf-8")):
            history.append({"date": today.isoformat(), "test": e["test"], "passed_on_retry": e["passed_on_retry"]})
    hp.write_text(json.dumps(history, indent=1), encoding="utf-8")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(render(history, today), encoding="utf-8")
    for t in quarantine_candidates(history, today):
        print(f"QUARANTINE: {t}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
