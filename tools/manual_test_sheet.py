"""Generate the owner's manual test sheet for one release (no network, standard library only).

    python tools/manual_test_sheet.py 4.0.0 [--changelog CHANGELOG.md] [--standing tools/manual_test_standing.toml]
                                      [--out docs/reviews/MANUAL_TEST_4.0.0.md]

Inputs: the version's section in CHANGELOG.md and the rows in manual_test_standing.toml. A row with `match = []`
is a standing row and is always in the sheet; a row with match words is included only when one of the words
appears in that version's CHANGELOG section. Rows are ordered by `order` so the owner can go top to bottom.
CHANGELOG items no row matched are listed under the table, so nothing new is silently untested.
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHECK = "[ ] pass [ ] fail [ ] blocked"


def _vkey(v: str) -> tuple[int, ...]:
    """'4.0.0' and '4.0' compare equal: trailing zero parts are dropped."""
    parts = [int(p) for p in re.findall(r"\d+", v.split("(")[0])[:4]]
    while parts and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def changelog_section(text: str, version: str) -> str:
    """Body of the '## <version> ...' section ('' when there is none)."""
    want = _vkey(version)
    body: list[str] | None = None
    for line in text.splitlines():
        m = re.match(r"##\s+v?(\d+(?:\.\d+)*)\b", line)
        if m:
            if body is not None:
                break
            if _vkey(m.group(1)) == want:
                body = []
            continue
        if body is not None:
            body.append(line)
    return "\n".join(body or []).strip()


def changelog_items(section: str) -> list[str]:
    """Each '- Added: a; b; c.' bullet becomes its parts: 'a', 'b', 'c' (the label word is dropped)."""
    items: list[str] = []
    for line in section.splitlines():
        m = re.match(r"\s*[-*]\s+(?:(?:Added|Changed|Fixed|Removed|Docs|Security|Deprecated)\s*:\s*)?(.*)", line)
        if not m:
            continue
        for part in re.split(r";\s+", m.group(1).strip().rstrip(".")):
            part = part.strip()
            if part:
                items.append(part)
    return items


def load_rows(path: Path) -> list[dict]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    rows = data.get("row", [])
    seen: set[int] = set()
    for r in rows:
        for k in ("order", "group", "do", "expect"):
            if k not in r:
                raise ValueError(f"row without '{k}': {r}")
        if r["order"] in seen:
            raise ValueError(f"duplicate order {r['order']}")
        seen.add(r["order"])
    return sorted(rows, key=lambda r: r["order"])


def select_rows(rows: list[dict], section: str) -> list[dict]:
    low = section.lower()
    return [r for r in rows if not r.get("match") or any(w.lower() in low for w in r["match"])]


def uncovered(items: list[str], rows: list[dict]) -> list[str]:
    """CHANGELOG items none of the selected rows mentions (by match word)."""
    words = [w.lower() for r in rows for w in r.get("match", [])]
    return [i for i in items if not any(w in i.lower() for w in words)]


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def render(version: str, rows: list[dict], items: list[str]) -> str:
    out = [f"# Manual test sheet: JARVES {version}", "",
           "For the owner, top to bottom, about 40 minutes. Mark one box per row. `optional` rows need an account "
           "you may have skipped: mark blocked and move on. Write a note for every fail. "
           "Generated by `tools/manual_test_sheet.py`; do not edit by hand, edit `tools/manual_test_standing.toml`.",
           ""]
    group = None
    n_opt = 0
    for i, r in enumerate(rows, 1):
        if r["group"] != group:
            group = r["group"]
            out += ["", f"## {group}", "", "| ID | Do | Expect | Result | Note |", "|---|---|---|---|---|"]
        opt = bool(r.get("optional"))
        n_opt += opt
        do = _cell(r["do"].replace("{version}", version))
        exp = _cell(r["expect"].replace("{version}", version))
        out.append(f"| M{i:02d}{' (optional)' if opt else ''} | {do} | {exp} | {CHECK} | |")
    out += ["", f"Rows: {len(rows)} ({n_opt} optional). Tester: ______  PC: ______  Date: ______", ""]
    miss = uncovered(items, rows)
    if miss:
        out += ["## Changelog items without a scripted row", "",
                "Try each once if you use it, and add a row to the standing file if it should be checked next time.", ""]
        out += [f"- {m}" for m in miss]
        out.append("")
    return "\n".join(out)


def build(version: str, changelog: Path, standing: Path) -> str:
    section = changelog_section(changelog.read_text(encoding="utf-8"), version)
    if not section:
        raise ValueError(f"no section for {version} in {changelog}")
    rows = select_rows(load_rows(standing), section)
    return render(version, rows, changelog_items(section))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("version")
    ap.add_argument("--changelog", type=Path, default=ROOT / "CHANGELOG.md")
    ap.add_argument("--standing", type=Path, default=ROOT / "tools" / "manual_test_standing.toml")
    ap.add_argument("--out", type=Path, default=None, help="default: docs/reviews/MANUAL_TEST_<version>.md")
    a = ap.parse_args(argv)
    try:
        text = build(a.version, a.changelog, a.standing)
    except (ValueError, OSError, tomllib.TOMLDecodeError) as e:
        print(f"manual_test_sheet: {e}", file=sys.stderr)
        return 2
    out = a.out or ROOT / "docs" / "reviews" / f"MANUAL_TEST_{a.version}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
